use std::fmt::Display;

use multiversx_sc::abi::{
    EndpointAbi, EndpointMutabilityAbi, EndpointTypeAbi, EnumVariantDescription, OutputAbi,
    StructFieldDescription, TypeContents, TypeDescription, TypeNames,
};

use crate::contract::sc_config::proxy_config::ProxyConfig;

use super::proxy_process_type_name::{
    c_enum_representation, explicit_discriminant, extract_paths, extract_struct_crate,
    process_rust_type,
};

const ZERO: &str = "0";

const PRELUDE: &str = "// Code generated by the multiversx-sc proxy generator. DO NOT EDIT.

////////////////////////////////////////////////////
////////////////// AUTO-GENERATED //////////////////
////////////////////////////////////////////////////

#![allow(dead_code)]
#![allow(clippy::all)]
";

/// The pure-ABI-typed source shapes `[[proxy]] format` can produce, alongside the legacy
/// `TxProxyTrait`-based `ProxyGenerator` output (`format = "proxy"`, the default, untouched).
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum AbiSourceMode {
    /// A `#[contract_abi(call = ...)]`-annotated trait: the *input* the macro consumes.
    Trait,
    /// The raw `AbiProxyTrait`/`ProxyArg`/`IntoXxx` implementation, hand-writable style
    /// (`contracts/examples/adder/src/adder_abi.rs`): what that macro *expands to*.
    Raw,
}

/// Generates framework-agnostic ABI source (see `AbiSourceMode`) from a `ContractAbi`, mirroring
/// `ProxyGenerator`'s structure but targeting `multiversx_sc_abi`'s `AbiProxyTrait` family
/// instead of the legacy `TxProxyTrait` one.
///
/// Type names are resolved via `TypeNames::pure_rust` (`<T::Abi as TypeAbi>::type_name_rust()`,
/// computed once at compile time when the original contract's ABI was built) for framework
/// types, and via the bare `TypeNames::abi` name for local custom struct/enum types, each of
/// which gets its own local, non-generic, pure-typed definition emitted by `write_types`.
pub struct AbiSourceGenerator<'a> {
    pub file: Option<&'a mut dyn std::io::Write>,
    pub proxy_config: &'a ProxyConfig,
    pub mode: AbiSourceMode,
    /// Local custom types skipped by `write_types` because a field had no pure ABI equivalent
    /// (a `$API`/`UncallableApi` residue) — consulted by `type_is_usable` so anything
    /// referencing one of these (a field of another type, or an endpoint arg/output) is also
    /// skipped, rather than emitted referencing a type that was never defined.
    unmappable_local_types: std::collections::HashSet<String>,
}

impl<'a> AbiSourceGenerator<'a> {
    pub fn new(
        file: &'a mut dyn std::io::Write,
        proxy_config: &'a ProxyConfig,
        mode: AbiSourceMode,
    ) -> Self {
        Self {
            file: Some(file),
            proxy_config,
            mode,
            unmappable_local_types: std::collections::HashSet::new(),
        }
    }

    fn write(&mut self, s: impl Display) {
        let file = self.file.as_mut().unwrap();
        file.write_all(s.to_string().as_bytes()).unwrap();
    }

    fn writeln(&mut self, s: impl Display) {
        self.write(s);
        self.write("\n");
    }

    pub fn write_to_file(&mut self) {
        self.write_header();
        self.write_types();
        match self.mode {
            AbiSourceMode::Trait => self.write_trait(),
            AbiSourceMode::Raw => self.write_raw(),
        }
    }

    fn write_header(&mut self) {
        self.writeln(PRELUDE);

        if !self.proxy_config.override_import.is_empty() {
            self.writeln(self.proxy_config.override_import.to_owned());
            return;
        }

        self.writeln("use multiversx_sc::abi::*;");
        // The local pure type definitions below (see `write_types`) never carry an `Api`
        // generic, so deriving them via the framework's own macros (already a dependency of
        // any crate this file lives in) is just as "pure" as a standalone equivalent would be —
        // `derive_imports` is the exact same bundle `abi_tester.rs` itself uses.
        self.writeln("use multiversx_sc::derive_imports::*;");
        // `pure_rust` leaves framework types with no `Api` generic (`H256`, `MultiValueN<...>`,
        // `OptionalValue<T>`, `ArrayVec<T, N>`, `Box<T>`, `OperationCompletionStatus`, ...)
        // referenced as-is, since they're already framework-agnostic - only `imports` exposes
        // them under their bare names.
        self.writeln("use multiversx_sc::imports::*;");
        if self.mode == AbiSourceMode::Trait {
            self.writeln("use multiversx_sc_abi_derive::contract_abi;");
        }
    }

    /// Resolves an ABI type reference to a pure Rust type name: the bare local name for a
    /// custom struct/enum this generator is about to emit a definition for (see `write_types`),
    /// otherwise the compile-time-computed `pure_rust` name (already fully resolved and
    /// correct, recursively, for every framework managed type).
    ///
    /// `pure_rust` is correct at the leaf level, but for a *composite* type (`Option<T>`,
    /// tuples, `MultiValueN<...>`, ...) wrapping a local custom struct/enum, the embedded
    /// inner type name is `T`'s own `type_name_rust()` — for a custom type that's always the
    /// full `core::any::type_name` path (`#[type_abi]` never overrides it), since only the
    /// *outer* wrapper's `Abi` projection ran, not a projection of the inner type itself. So
    /// every occurrence still needs the same local-path-stripping pass `clean_local_paths`
    /// applies to the whole string, exactly mirroring what `ProxyGenerator::clean_paths` does
    /// for `.rust` names.
    fn abi_type(&self, type_names: &TypeNames) -> String {
        if self.is_local_type_name(&type_names.abi) {
            return type_names.abi.clone();
        }
        self.clean_local_paths(&type_names.pure_rust)
    }

    fn is_local_type_name(&self, abi_name: &str) -> bool {
        self.proxy_config
            .abi
            .type_descriptions
            .find(abi_name)
            .is_some_and(|desc| desc.contents.is_specified())
    }

    /// Strips every embedded path down to its bare local name when that name is one of our own
    /// local types (see `write_types`) — the same technique `ProxyGenerator::clean_paths` uses
    /// for `.rust` names, applied to `pure_rust` strings instead. Paths that aren't local types
    /// (external crates, or a residual `$API`/`UncallableApi` placeholder left over from a
    /// managed type with no registered pure ABI equivalent) are left untouched.
    fn clean_local_paths(&self, rust_type: &str) -> String {
        let paths = extract_paths(rust_type);
        let processed_paths: Vec<String> = paths
            .iter()
            .map(|path| {
                let bare_name = path.rsplit("::").next().unwrap_or(path);
                if self.is_local_type_name(bare_name) {
                    bare_name.to_string()
                } else {
                    path.clone()
                }
            })
            .collect();
        process_rust_type(rust_type.to_string(), paths, processed_paths)
    }

    /// A type with no pure ABI equivalent (no `Abi` projection override, and not one of our own
    /// local types) leaves a literal `$API`/`UncallableApi` marker behind — that's not valid
    /// Rust, so anything referencing it must be skipped rather than emitted broken.
    fn has_unmapped_api_residue(rust_type: &str) -> bool {
        rust_type.contains("$API") || rust_type.contains("UncallableApi")
    }

    /// False when `type_names` resolves to something unusable: leftover API residue, or (for a
    /// local custom type) one `write_types` already decided to skip for the same reason.
    fn type_is_usable(&self, type_names: &TypeNames) -> bool {
        if self.unmappable_local_types.contains(&type_names.abi) {
            return false;
        }
        !Self::has_unmapped_api_residue(&self.abi_type(type_names))
    }

    fn has_path_rename_for_crate(&self, rust_name: &str) -> bool {
        let crate_prefix = extract_struct_crate(rust_name);
        self.proxy_config
            .path_rename
            .iter()
            .any(|pr| pr.from == crate_prefix)
    }

    // ---- exported functions (constructors / upgrades / endpoints) ----

    /// Takes `proxy_config` directly (rather than `&self`) so the returned borrow is tied to
    /// `'a` (the `ProxyConfig` reference's own lifetime) instead of to a `&self` call — letting
    /// callers iterate the result while still holding `&mut self` for `write_trait_method`/
    /// `write_raw_method`.
    fn exported_endpoints(proxy_config: &'a ProxyConfig) -> Vec<&'a EndpointAbi> {
        proxy_config
            .abi
            .constructors
            .iter()
            .chain(proxy_config.abi.upgrade_constructors.iter())
            .chain(proxy_config.abi.endpoints.iter())
            .collect()
    }

    fn output_type(&self, outputs: &[OutputAbi]) -> String {
        match outputs.len() {
            0 => "()".to_string(),
            1 => self.abi_type(&outputs[0].type_names),
            _ => {
                let inner: Vec<String> = outputs
                    .iter()
                    .map(|o| self.abi_type(&o.type_names))
                    .collect();
                format!("MultiValue{}<{}>", outputs.len(), inner.join(", "))
            }
        }
    }

    // ---- Trait mode ----

    fn write_trait(&mut self) {
        let call_name =
            super::proxy_process_type_name::proxy_type_name(&self.proxy_config.abi.name);
        self.writeln(format!(
            "\n#[contract_abi(call = {call_name})]\npub trait {} {{",
            self.proxy_config.abi.name
        ));

        for endpoint in Self::exported_endpoints(self.proxy_config) {
            self.write_trait_method(endpoint);
        }

        self.writeln("}");
    }

    fn endpoint_is_usable(&self, endpoint: &EndpointAbi) -> bool {
        endpoint
            .inputs
            .iter()
            .all(|input| self.type_is_usable(&input.type_names))
            && endpoint
                .outputs
                .iter()
                .all(|output| self.type_is_usable(&output.type_names))
    }

    fn write_trait_method(&mut self, endpoint: &EndpointAbi) {
        if !self.endpoint_is_usable(endpoint) {
            self.writeln(format!(
                "\n    // Skipped: endpoint '{}' uses a type with no pure ABI equivalent.",
                endpoint.name
            ));
            return;
        }

        for doc in &endpoint.docs {
            self.writeln(format!("    /// {doc}"));
        }
        if endpoint.allow_multiple_var_args {
            self.writeln("    #[allow_multiple_var_args]");
        }
        if endpoint.only_owner {
            self.writeln("    #[only_owner]");
        }
        if endpoint.only_admin {
            self.writeln("    #[only_admin]");
        }
        for token in &endpoint.payable_in_tokens {
            self.writeln(format!("    #[payable(\"{token}\")]"));
        }
        self.writeln(match endpoint.endpoint_type {
            EndpointTypeAbi::Init => "    #[init]".to_string(),
            EndpointTypeAbi::Upgrade => "    #[upgrade]".to_string(),
            EndpointTypeAbi::PromisesCallback => return, // no external call surface
            EndpointTypeAbi::Endpoint => match endpoint.mutability {
                EndpointMutabilityAbi::Readonly | EndpointMutabilityAbi::Pure => {
                    format!("    #[view({})]", endpoint.name)
                }
                EndpointMutabilityAbi::Mutable => format!("    #[endpoint({})]", endpoint.name),
            },
        });

        let args: Vec<String> = endpoint
            .inputs
            .iter()
            .map(|input| format!("{}: {}", input.arg_name, self.abi_type(&input.type_names)))
            .collect();

        let return_part = if endpoint.outputs.is_empty() {
            String::new()
        } else {
            format!(" -> {}", self.output_type(&endpoint.outputs))
        };

        self.writeln(format!(
            "    fn {}(&self{}{}){};\n",
            endpoint.rust_method_name,
            if args.is_empty() { "" } else { ", " },
            args.join(", "),
            return_part
        ));
    }

    // ---- Raw mode ----

    fn write_raw(&mut self) {
        let proxy_name =
            super::proxy_process_type_name::proxy_type_name(&self.proxy_config.abi.name);
        let methods_name =
            super::proxy_process_type_name::proxy_methods_type_name(&self.proxy_config.abi.name);

        self.writeln("\nuse multiversx_sc::abi::ApplyArgument as _;\n");
        self.writeln(format!("pub struct {proxy_name};\n"));
        self.writeln(format!(
            "impl<T> AbiProxyTrait<T> for {proxy_name} {{\n    type Methods = {methods_name}<T>;\n\n    fn proxy_methods(self, base_tx: T) -> Self::Methods {{\n        {methods_name} {{ base_tx }}\n    }}\n}}\n"
        ));
        self.writeln(format!(
            "pub struct {methods_name}<T> {{\n    base_tx: T,\n}}"
        ));

        for endpoint in Self::exported_endpoints(self.proxy_config) {
            self.write_raw_method(endpoint, &methods_name);
        }
    }

    fn write_raw_method(&mut self, endpoint: &EndpointAbi, methods_name: &str) {
        if matches!(endpoint.endpoint_type, EndpointTypeAbi::PromisesCallback) {
            return; // no external call surface
        }
        if !self.endpoint_is_usable(endpoint) {
            self.writeln(format!(
                "\n// Skipped: endpoint '{}' uses a type with no pure ABI equivalent.",
                endpoint.name
            ));
            return;
        }

        let payable = !endpoint.payable_in_tokens.is_empty();
        let output_ty = self.output_type(&endpoint.outputs);

        let (into_trait, into_method, extra_generic, payment_param, call_args): (
            String,
            &str,
            &str,
            &str,
            String,
        ) = match endpoint.endpoint_type {
            EndpointTypeAbi::Init => (
                format!(
                    "IntoDeploy<{}, {output_ty}>",
                    if payable { "Payment" } else { "NotPayable" }
                ),
                "into_deploy",
                if payable { "Payment, " } else { "" },
                if payable { "payment: Payment, " } else { "" },
                (if payable { "payment" } else { "NotPayable" }).to_string(),
            ),
            EndpointTypeAbi::Upgrade => (
                format!(
                    "IntoUpgrade<{}, {output_ty}>",
                    if payable { "Payment" } else { "NotPayable" }
                ),
                "into_upgrade",
                if payable { "Payment, " } else { "" },
                if payable { "payment: Payment, " } else { "" },
                (if payable { "payment" } else { "NotPayable" }).to_string(),
            ),
            EndpointTypeAbi::Endpoint => (
                format!(
                    "IntoCall<{}, {output_ty}>",
                    if payable { "Payment" } else { "NotPayable" }
                ),
                "into_call",
                if payable { "Payment, " } else { "" },
                if payable { "payment: Payment, " } else { "" },
                format!(
                    "{}, \"{}\"",
                    if payable { "payment" } else { "NotPayable" },
                    endpoint.name
                ),
            ),
            EndpointTypeAbi::PromisesCallback => unreachable!(),
        };

        let arg_generics: Vec<String> = endpoint
            .inputs
            .iter()
            .enumerate()
            .map(|(i, input)| format!("Arg{i}: ProxyArg<{}>", self.abi_type(&input.type_names)))
            .collect();
        let arg_params: Vec<String> = endpoint
            .inputs
            .iter()
            .enumerate()
            .map(|(i, input)| format!("{}: Arg{i}", input.arg_name))
            .collect();
        let apply_args: String = endpoint
            .inputs
            .iter()
            .map(|input| format!("\n            .apply_argument(&{})", input.arg_name))
            .collect();

        self.writeln(format!(
            "\nimpl<T> {methods_name}<T> {{\n    pub fn {}<{extra_generic}{}>(\n        self,\n        {payment_param}{}\n    ) -> <T as {into_trait}>::Out\n    where\n        T: {into_trait},\n    {{\n        self.base_tx\n            .{into_method}({call_args}){apply_args}\n    }}\n}}",
            endpoint.rust_method_name,
            arg_generics.join(", "),
            arg_params.join(", "),
        ));
    }

    // ---- local type definitions (structs / enums), shared by both modes ----

    fn write_types(&mut self) {
        let type_descriptions = self.proxy_config.abi.type_descriptions.0.clone();
        for (_, type_description) in &type_descriptions {
            if !type_description.contents.is_specified() {
                continue;
            }
            let rust_name = type_description.names.rust.as_str();
            if self.has_path_rename_for_crate(rust_name) {
                continue;
            }

            let name = type_description.names.abi.clone();
            match &type_description.contents {
                TypeContents::Enum(variants) => self.write_enum(variants, type_description, &name),
                TypeContents::Struct(fields) => self.write_struct(fields, type_description, &name),
                TypeContents::ExplicitEnum(_) | TypeContents::NotSpecified => {}
            }
        }
    }

    fn write_enum(
        &mut self,
        enum_variants: &[EnumVariantDescription],
        type_description: &TypeDescription,
        name: &str,
    ) {
        let all_fields_usable = enum_variants
            .iter()
            .flat_map(|variant| variant.fields.iter())
            .all(|field| self.type_is_usable(&field.field_type));
        if !all_fields_usable {
            self.unmappable_local_types.insert(name.to_string());
            self.writeln(format!(
                "\n// Skipped: enum '{name}' has a field with no pure ABI equivalent."
            ));
            return;
        }

        if self.enum_contains_struct_variant(enum_variants) {
            self.write("\n#[rustfmt::skip]");
            if let Some(c_type) = c_enum_representation(enum_variants) {
                self.write(format!("\n#[repr({c_type})]"));
            }
        }

        self.write_macro_attributes(&type_description.macro_attributes);
        self.write(format!("pub enum {name}"));

        if enum_variants.is_empty() {
            self.writeln(" {}");
            return;
        }

        self.writeln(" {");
        for (i, variant) in enum_variants.iter().enumerate() {
            self.write(format!("    {}", variant.name));
            let discriminant = explicit_discriminant(i, variant, enum_variants);

            if variant.fields.is_empty() {
                if discriminant.is_some() {
                    self.write(format!(" = {}", variant.discriminant));
                }
                self.writeln(",");
                continue;
            }

            if variant.fields[0].name == ZERO {
                self.write_tuple_fields(&variant.fields, discriminant, ',');
            } else {
                self.write_struct_variant_fields(&variant.fields, discriminant);
            }
        }
        self.writeln("}");
    }

    fn write_struct(
        &mut self,
        struct_fields: &[StructFieldDescription],
        type_description: &TypeDescription,
        name: &str,
    ) {
        if struct_fields
            .iter()
            .any(|field| !self.type_is_usable(&field.field_type))
        {
            self.unmappable_local_types.insert(name.to_string());
            self.writeln(format!(
                "\n// Skipped: struct '{name}' has a field with no pure ABI equivalent."
            ));
            return;
        }

        self.write_macro_attributes(&type_description.macro_attributes);
        self.write(format!("pub struct {name}"));

        if struct_fields.is_empty() {
            self.writeln(" {}");
            return;
        }

        if struct_fields.len() == 1 && struct_fields[0].name == ZERO {
            self.write_tuple_fields(struct_fields, None, ';');
            return;
        }

        self.writeln(" {");
        for field in struct_fields {
            let field_type = self.abi_type(&field.field_type);
            self.writeln(format!("    pub {}: {field_type},", field.name));
        }
        self.writeln("}");
    }

    fn write_tuple_fields(
        &mut self,
        fields: &[StructFieldDescription],
        discriminant: Option<usize>,
        punctuation: char,
    ) {
        self.write("(");
        for (i, field) in fields.iter().enumerate() {
            if i > 0 {
                self.write(", ");
            }
            self.write(self.abi_type(&field.field_type));
        }
        match discriminant {
            Some(d) => self.write(format!(") = {d}{punctuation}")),
            None => self.writeln(format!("){punctuation}")),
        }
    }

    fn write_struct_variant_fields(
        &mut self,
        fields: &[StructFieldDescription],
        discriminant: Option<usize>,
    ) {
        self.writeln(" {");
        for field in fields {
            let field_type = self.abi_type(&field.field_type);
            self.writeln(format!("        {}: {field_type},", field.name));
        }
        self.write("    }");
        if let Some(d) = discriminant {
            self.write(format!(" = {d}"));
        }
        self.writeln(",");
    }

    /// Unlike `ProxyGenerator` (which reconstructs real, encodable managed types and so keeps
    /// the original `TopEncode`/`TopDecode`/`Clone`/`Debug`/... derives), these local
    /// definitions only ever compose pure ABI marker types (`BigUintAbi`, `AddressAbi`,
    /// `ListAbi<T>`, ...), which themselves derive *nothing* beyond `TypeAbi` — they're never
    /// instantiated, only used as type-level markers (e.g. `ProxyArg<BigUintAbi>`). `TypeAbi`
    /// has no `TopEncode`/`Clone`/etc. bound, so `#[type_abi]` alone is both sufficient and the
    /// only thing that would actually compile here.
    fn write_macro_attributes(&mut self, macro_attributes: &[String]) {
        self.writeln("");
        for attr in macro_attributes {
            if attr.contains("::") {
                self.writeln(format!("#[{attr}]"));
            }
        }
        self.writeln("#[type_abi]");
    }

    fn enum_contains_struct_variant(&self, enum_variants: &[EnumVariantDescription]) -> bool {
        enum_variants
            .iter()
            .any(|variant| !variant.fields.is_empty() && variant.fields[0].name != ZERO)
    }
}
